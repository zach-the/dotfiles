#!/usr/bin/env python3
"""Render the three states of the waybar custom/scrollsesh glyph: a simple
padlock, in the same flat-white / translucent-dim visual language as
generate_jellyfin_icons.py.
  locked.svg:   solid white closed padlock   (blocked, sessions available)
  unlocked.svg: solid white open padlock     (session active)
  empty.svg:    dimmed closed padlock        (blocked, no sessions left today)

Output: waybar/icons/scrollsesh/{locked,unlocked,empty}.svg, plus
waybar/scrollsesh-icons-generated.css, which style.css @imports, mapping
the locked/active/empty classes `scrollsesh status --waybar` sets to the
matching background-image.

Run manually to regenerate: ./generate_scrollsesh_icons.py
"""
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent
ICONS_DIR = ROOT / "icons" / "scrollsesh"
CSS_OUT = ROOT / "scrollsesh-icons-generated.css"

WHITE = "#ffffff"
DIM_OPACITY = "0.3"

BODY = '<rect x="5" y="11" width="14" height="10" rx="2" fill="{c}" fill-opacity="{op}"/>'
SHACKLE_CLOSED = ('<path d="M8 11V8a4 4 0 0 1 8 0v3" stroke="{c}" stroke-opacity="{op}" '
                   'stroke-width="2.2" fill="none" stroke-linecap="round"/>')
# Same arc as SHACKLE_CLOSED, rotated open around its right anchor point so
# the left leg swings up and away from the body -- an "unlocked, shackle
# popped open" silhouette rather than a second closed lock.
SHACKLE_OPEN = ('<path d="M8 11V8a4 4 0 0 1 8 0v1" stroke="{c}" stroke-opacity="{op}" '
                 'stroke-width="2.2" fill="none" stroke-linecap="round" transform="rotate(35 16 8)"/>')


def glyph(opacity, open_shackle):
    shackle = SHACKLE_OPEN if open_shackle else SHACKLE_CLOSED
    return BODY.format(c=WHITE, op=opacity) + shackle.format(c=WHITE, op=opacity)


def svg(shapes):
    return f'<svg width="24" height="24" viewBox="0 0 24 24" xmlns="http://www.w3.org/2000/svg">{shapes}</svg>'


def main():
    if ICONS_DIR.exists():
        shutil.rmtree(ICONS_DIR)
    ICONS_DIR.mkdir(parents=True)

    locked_path = ICONS_DIR / "locked.svg"
    unlocked_path = ICONS_DIR / "unlocked.svg"
    empty_path = ICONS_DIR / "empty.svg"
    locked_path.write_text(svg(glyph("1", False)))
    unlocked_path.write_text(svg(glyph("1", True)))
    empty_path.write_text(svg(glyph(DIM_OPACITY, False)))

    css = (
        "/* GENERATED by generate_scrollsesh_icons.py -- do not edit by hand */\n"
        f'#custom-scrollsesh.locked {{ background-image: url("file://{locked_path}"); }}\n'
        f'#custom-scrollsesh.active {{ background-image: url("file://{unlocked_path}"); }}\n'
        f'#custom-scrollsesh.empty {{ background-image: url("file://{empty_path}"); }}\n'
    )
    CSS_OUT.write_text(css)
    print(f"Wrote {locked_path}, {unlocked_path}, {empty_path}")
    print(f"Wrote {CSS_OUT}")


if __name__ == "__main__":
    main()
