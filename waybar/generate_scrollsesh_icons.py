#!/usr/bin/env python3
"""Render the waybar custom/scrollsesh glyph: a ring, in the same flat-
white / translucent-dim visual language as generate_jellyfin_icons.py's
on/off treatment.
  locked.svg:  a full-opacity ring   (blocked, sessions available)
  empty.svg:   a dimmed ring         (blocked, no sessions left today)
  pNN.svg:     the same ring, geometry never changing, faded to NN% of the
               way from full-opacity white toward the dimmed/translucent
               look -- NN is the fraction of the current session's time
               still remaining, so it reads as bright white at session
               start and gradually dims toward the same translucent grey
               as "empty" by the time it runs out (a fade, not a pie wedge
               or a loading spinner).

Output: waybar/icons/scrollsesh/{locked,empty,p0,p2,...,p100}.svg, plus
waybar/scrollsesh-icons-generated.css, which style.css @imports, mapping
the classes `scrollsesh status --waybar` sets (see _RING_STEP there, which
must match RING_STEP here) to the matching background-image.

Run manually to regenerate: ./generate_scrollsesh_icons.py
"""
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent
ICONS_DIR = ROOT / "icons" / "scrollsesh"
CSS_OUT = ROOT / "scrollsesh-icons-generated.css"

WHITE = "#ffffff"
DIM_OPACITY = 0.3
SIZE = 24
CX = CY = 12
R = 9
STROKE = 2.2

# Percentage step between generated fade frames -- must match scrollsesh's
# own _RING_STEP constant (waybar polls every 5s, and a 3-minute default
# session is ~36 polls, so 2% keeps every tick distinct without generating
# more frames than could ever actually be shown).
RING_STEP = 2


def svg(shapes):
    return f'<svg width="{SIZE}" height="{SIZE}" viewBox="0 0 {SIZE} {SIZE}" xmlns="http://www.w3.org/2000/svg">{shapes}</svg>'


def ring(opacity):
    return (f'<circle cx="{CX}" cy="{CY}" r="{R}" fill="none" '
            f'stroke="{WHITE}" stroke-opacity="{opacity:.3f}" stroke-width="{STROKE}"/>')


def fade_opacity(fraction_remaining):
    """fraction_remaining=1 (session just started) -> fully opaque, same as
    "locked"; fraction_remaining=0 (out of time) -> DIM_OPACITY, same as
    "empty" -- a continuous fade between the two existing looks rather than
    a third visual language."""
    return DIM_OPACITY + fraction_remaining * (1 - DIM_OPACITY)


def main():
    if ICONS_DIR.exists():
        shutil.rmtree(ICONS_DIR)
    ICONS_DIR.mkdir(parents=True)

    css_lines = ["/* GENERATED by generate_scrollsesh_icons.py -- do not edit by hand */"]

    locked_path = ICONS_DIR / "locked.svg"
    locked_path.write_text(svg(ring(1.0)))
    css_lines.append(f'#custom-scrollsesh.locked {{ background-image: url("file://{locked_path}"); }}')

    empty_path = ICONS_DIR / "empty.svg"
    empty_path.write_text(svg(ring(DIM_OPACITY)))
    css_lines.append(f'#custom-scrollsesh.empty {{ background-image: url("file://{empty_path}"); }}')

    for pct in range(0, 101, RING_STEP):
        p = ICONS_DIR / f"p{pct}.svg"
        p.write_text(svg(ring(fade_opacity(pct / 100))))
        css_lines.append(f'#custom-scrollsesh.p{pct} {{ background-image: url("file://{p}"); }}')

    CSS_OUT.write_text("\n".join(css_lines) + "\n")
    print(f"Wrote {len(list(ICONS_DIR.iterdir()))} icons to {ICONS_DIR}")
    print(f"Wrote {CSS_OUT}")


if __name__ == "__main__":
    main()
