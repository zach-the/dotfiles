#!/usr/bin/env python3
"""Render the waybar custom/mic glyph: Lucide's "mic" icon (MIT
licensed) rebuilt as filled primitives -- just the mic itself, two
states (unmuted/muted), no level rings (unlike
generate_volume_icons.py's speaker: mic *input* gain isn't something
you'd gauge at a glance the way output loudness is, so there's nothing
worth growing/shrinking here).

The capsule is Lucide's path verbatim -- it's already one closed
outline, so it's fillable with no stroke-to-fill conversion needed.
The stand bracket and stem, stroked in the original (stroke-width 2),
are rebuilt here as a filled ring band (_arc_band) plus two short leg
rects and a stem rect, each exactly replacing a stroke of width 2 with
a filled shape of the same footprint -- see stand()'s call sites for
the arithmetic.

Output: waybar/icons/mic/{mic,muted}.svg, plus
waybar/mic-icons-generated.css, which style.css @imports, mapping
those two classes (set by mic_color.py) to the matching
background-image.

Run manually to regenerate: ./generate_mic_icons.py
"""
import math
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent
ICONS_DIR = ROOT / "icons" / "mic"
CSS_OUT = ROOT / "mic-icons-generated.css"

WHITE = "#ffffff"
DIM_OPACITY = "0.3"

# Lucide's mic capsule path (https://lucide.dev, MIT), unmodified --
# a closed outline (two straight sides + a radius-3 arc at each end),
# so it fills directly instead of needing a stroke-to-fill conversion.
CAPSULE_PATH = "M12 2a3 3 0 0 0-3 3v7a3 3 0 0 0 6 0V5a3 3 0 0 0-3-3Z"


def capsule(opacity="1"):
    return f'<path d="{CAPSULE_PATH}" fill="{WHITE}" fill-opacity="{opacity}"/>'


def _arc_point(cx, cy, r, deg):
    rad = math.radians(deg)
    return cx + r * math.cos(rad), cy + r * math.sin(rad)


def _arc_band(cx, cy, r_in, r_out, start_deg, end_deg, opacity="1"):
    """Filled band between two concentric arcs -- used only for the
    stand bracket's curve."""
    xi0, yi0 = _arc_point(cx, cy, r_in, start_deg)
    xi1, yi1 = _arc_point(cx, cy, r_in, end_deg)
    xo1, yo1 = _arc_point(cx, cy, r_out, end_deg)
    xo0, yo0 = _arc_point(cx, cy, r_out, start_deg)
    d = (
        f'M{xi0:.3f} {yi0:.3f} '
        f'A{r_in} {r_in} 0 0 1 {xi1:.3f} {yi1:.3f} '
        f'L{xo1:.3f} {yo1:.3f} '
        f'A{r_out} {r_out} 0 0 0 {xo0:.3f} {yo0:.3f} Z'
    )
    return f'<path d="{d}" fill="{WHITE}" fill-opacity="{opacity}"/>'


# Lucide's stand, stroked: "M19 10v2a7 7 0 0 1-14 0v-2" (a 7-radius
# lower semicircle centered on (12,12), from (19,10)-(19,12) down to
# (5,10)-(5,12)) + a stem line x=12 from y19 to y22. Stroke-width 2
# means the true drawn shape spans +-1 around each of those numbers --
# the band/rects below reproduce exactly that footprint filled.
STAND_CENTER = (12, 12)
STAND_R_IN, STAND_R_OUT = 6, 8  # 7 -+ 1
LEG_Y0, LEG_Y1 = 10, 12


def stand(opacity="1"):
    cx, cy = STAND_CENTER
    band = _arc_band(cx, cy, STAND_R_IN, STAND_R_OUT, 0, 180, opacity=opacity)
    # Legs sit at the band's own open ends (x = cx -+ r, for r in
    # [r_in, r_out]) so they meet the curve with no seam.
    left_leg = f'<rect x="{cx - STAND_R_OUT}" y="{LEG_Y0}" width="{STAND_R_OUT - STAND_R_IN}" height="{LEG_Y1 - LEG_Y0}" fill="{WHITE}" fill-opacity="{opacity}"/>'
    right_leg = f'<rect x="{cx + STAND_R_IN}" y="{LEG_Y0}" width="{STAND_R_OUT - STAND_R_IN}" height="{LEG_Y1 - LEG_Y0}" fill="{WHITE}" fill-opacity="{opacity}"/>'
    stem = f'<rect x="{cx - 1}" y="19" width="2" height="3" fill="{WHITE}" fill-opacity="{opacity}"/>'
    return band + left_leg + right_leg + stem


def mic_body(opacity="1"):
    return capsule(opacity) + stand(opacity)


SLASH = f'<line x1="2" y1="4" x2="16" y2="20" stroke="{WHITE}" stroke-opacity="{DIM_OPACITY}" stroke-width="1.8" stroke-linecap="round"/>'

FILES = {
    "mic": mic_body(),
    "muted": mic_body(DIM_OPACITY) + SLASH,
}


VIEW_W, VIEW_H = 24, 24  # just the glyph -- no rings to leave room for


def svg(shapes):
    # Large intrinsic width/height vs. the viewBox, same reasoning as
    # generate_volume_icons.py: GTK rasterizes once at the declared
    # intrinsic size, so a small one makes for a blurry upscale.
    return (
        f'<svg width="{VIEW_W * 16}" height="{VIEW_H * 16}" viewBox="0 0 {VIEW_W} {VIEW_H}" '
        f'xmlns="http://www.w3.org/2000/svg">{shapes}</svg>'
    )


def main():
    if ICONS_DIR.exists():
        shutil.rmtree(ICONS_DIR)
    ICONS_DIR.mkdir(parents=True)

    css_rules = ["/* GENERATED by generate_mic_icons.py -- do not edit by hand */"]
    for name, shapes in FILES.items():
        out_path = ICONS_DIR / f"{name}.svg"
        out_path.write_text(svg(shapes))
        css_rules.append(f'#custom-mic.{name} {{ background-image: url("file://{out_path}"); }}')

    CSS_OUT.write_text("\n".join(css_rules) + "\n")
    print(f"Wrote {len(list(ICONS_DIR.glob('*.svg')))} icons to {ICONS_DIR}")
    print(f"Wrote {CSS_OUT}")


if __name__ == "__main__":
    main()
