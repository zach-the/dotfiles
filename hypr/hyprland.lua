-- =====================================================================
-- hyprland.lua — translated from hyprland.conf (Hyprland 0.55+ Lua config)
-- =====================================================================
-- This is a best-effort 1:1 port of hyprland.conf into the new Lua
-- config format. hyprland.conf is left in place, untouched, as a
-- fallback — but see the warning below before you rely on that.
--
-- IMPORTANT — this is NOT a side-by-side test file. If both
-- hyprland.conf and hyprland.lua exist in ~/.config/hypr (they will,
-- since this repo's hypr/ directory is symlinked there wholesale by
-- install.sh), Hyprland loads hyprland.lua INSTEAD of hyprland.conf,
-- full stop, the moment config is (re)loaded — which happens
-- automatically on save unless misc.disable_autoreload is set. So the
-- instant this file is saved into the repo, it is one reload away from
-- being live. To back out, delete or rename this file and reload —
-- hyprland.conf takes over again immediately, unchanged.
--
-- Known compatibility gaps from the straight .conf -> .lua port:
--
--  1. colors.conf (generated by generate_colors.py) is hyprlang syntax
--     and can't be `source`d from Lua. generate_colors.py now also
--     writes hypr/colors.lua (plain Lua data, same 4 values) alongside
--     it, and the LOOK AND FEEL section below reads that with
--     loadfile() — so rerunning generate_colors.py with a different
--     palette keeps working with no extra step. A hardcoded snapshot
--     is kept only as a last-resort fallback, for before
--     generate_colors.py has ever run.
--
--  2. monitors.conf (generated by nwg-displays, gitignored) is old-
--     format and can't be `source`d from Lua. Rather than maintaining
--     a separate conversion step, the MONITORS section below just
--     parses monitors.conf's `monitor=...` lines directly with a
--     small Lua function, on every config load. So saving a layout in
--     nwg-displays (SUPER+I) keeps working with no extra step —
--     whatever it writes gets picked up on the next reload (which
--     nwg-displays triggers itself). A hardcoded snapshot is kept only
--     as a last-resort fallback, for the case where monitors.conf
--     doesn't exist yet (e.g. brand new install, before nwg-displays
--     has ever saved a layout).
--
--  3. mode_toggle.sh (hyper+Space, WIDE-TILE/FLOAT toggle) needed NO
--     changes. It already writes a plain-text state file
--     (~/.config/hypr/mode_state, just the mode name) that both
--     configs can consume independently: hyprland.conf still sources
--     the old mode_float_rule.conf/mode_layout.conf fragments it also
--     writes, and this file reads mode_state directly (right after the
--     hyper+Space bind, in KEYBINDINGS below) and derives the same two
--     effects (layout + float-everything rule) natively. This also
--     means either config format works no matter which one is active,
--     so the toggle can't get stranded mid-migration.
-- =====================================================================

-- =====================================================================
-- HYPER (Ctrl+Alt+Shift+Super) KEYBIND MAP  —  [X] = bound   [ ] = free
-- =====================================================================
-- One merged keymap, identical in WIDE-TILE and FLOAT (see hyper+Space
-- below — it now only switches tiling algorithm / auto-float-new-window
-- behavior, not keybinds). The window-snap keys (halves/thirds/quarters/
-- maximize/center/resize) are floating-window actions mirroring
-- hammerspoon-init.lua; on a tiled window in WIDE-TILE mode they may
-- only partially apply (e.g. resize can nudge the tiling split while
-- the move half of the same action is ignored) rather than snapping
-- cleanly, since Hyprland's move/resize dispatchers are floating-first.
--
--  [ ][ ][ ][ ][4][5][6][7][8][9][0][-][=]
--    [Q][W][E][R][T][Y][U][I][O][P]
--      [A][S][D][F][G][H][J][K][L]
--         [Z][X][C][V][B][N][M]
--
--                                       [ RETURN ]
--
--   Q          → kill active window
--   W E        → two-thirds(1) / two-thirds(2)
--   R          → app launcher (rofi)
--   T          → launch terminal
--   Y / O      → move window to prev / next display
--   U I        → top-left / top-right quarter
--   P          → toggle floating for the whole workspace
--   A S D      → thirds(1) / thirds(2) / thirds(3) window snap
--   F          → maximize
--   G          → center window
--   H / L      → prev / next workspace (also left/right arrow)
--   J K        → bottom-left / bottom-right quarter
--   Z X C      → half-split (context-aware: portrait vs. landscape)
--   B          → send window to back of stack, focus new top window
--   N / M      → browser (personal profile) / browser (work profile)
--   BACKSPACE  → lock screen
--   RETURN     → fullscreen
--   SPACE      → toggle WIDE-TILE ↔ FLOAT (layout/auto-float only now)
--   0          → insert empty workspace to the right, shifting the rest
--   - =        → resize smaller / larger
--   4 5 6      → sixths: upper-left / upper-middle / upper-right
--   7 8 9      → sixths: lower-left / lower-middle / lower-right
--   left/right-drag anywhere on window → move / resize
--
--   FREE: 1 2 3 V
--   UNASSIGNED: per-window floating toggle (was F) has no key right now
-- =====================================================================

