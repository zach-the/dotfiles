-- Replaces the old `source = mode_float_rule.conf` / `source =
-- mode_layout.conf` includes. mode_toggle.sh (hyper+Space) already
-- writes the current mode name as plain text to mode_state — this
-- reads it directly and re-derives the same two effects it used to
-- express via those sourced fragments. See the compatibility note at
-- the top of this file.
local function read_mode_state()
    local f = io.open(os.getenv("HOME") .. "/.config/hypr/mode_state", "r")
    if not f then return "WIDE-TILE" end
    local mode = f:read("l")
    f:close()
    return mode or "WIDE-TILE"
end

