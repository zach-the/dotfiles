-- COLORS — generate_colors.py (from palettes/dark.toml) writes this
-- directly as Lua (hypr/colors.lua), alongside the old hypr/colors.conf
-- it writes for hyprland.conf's benefit. Read fresh on every config
-- load, so repainting the palette just needs a re-run + reload, same
-- as before.
local function load_colors()
    local chunk = loadfile(os.getenv("HOME") .. "/.config/hypr/colors.lua")
    if not chunk then return nil end
    local ok, result = pcall(chunk)
    if not ok then return nil end
    return result
end

