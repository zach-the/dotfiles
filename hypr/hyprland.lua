-- MONITORS - managed by nwg-displays (SUPER+I). nwg-displays has no Lua
-- output option, and there's no `source`/`require` for its old-format
-- monitors.conf from here, so this just parses its `monitor=...` lines
-- directly, fresh on every config load. See the compatibility note at
-- the top of this file.
local function monitors_from_conf()
    local f = io.open(os.getenv("HOME") .. "/.config/hypr/monitors.conf", "r")
    if not f then return {} end

    local specs = {}
    for line in f:lines() do
        local rest = line:match("^%s*monitor%s*=%s*(.*)$")
        if rest then
            local fields = {}
            for field in (rest .. ","):gmatch("([^,]*),") do
                table.insert(fields, field:match("^%s*(.-)%s*$"))
            end
            if fields[1] and fields[1] ~= "" then
                local spec = {
                    output   = fields[1],
                    mode     = (fields[2] and fields[2] ~= "") and fields[2] or "preferred",
                    position = (fields[3] and fields[3] ~= "") and fields[3] or "auto",
                    scale    = (fields[4] and fields[4] ~= "") and (tonumber(fields[4]) or fields[4]) or "auto",
                }
                local i = 5
                while fields[i] and fields[i + 1] and fields[i + 1] ~= "" do
                    local key, val = fields[i], fields[i + 1]
                    if key == "vrr" or key == "transform" or key == "bitdepth" then
                        spec[key] = tonumber(val)
                    end
                    i = i + 2
                end
                table.insert(specs, spec)
            end
        end
    end
    f:close()
    return specs
end

