-- popup_daemon.py's GTK popups (audio/wifi/bluetooth/jellyfin/power) all
-- share the layer-shell namespace "popup-daemon" (see each *_popup.py's
-- GtkLayerShell.set_namespace call). Their CSS background is translucent
-- grey (waybar/../popup_theme.css) for a frosted, macOS-vibrancy look --
-- this is what actually blurs the desktop behind that alpha. ignore_alpha
-- keeps the blur off the fully-transparent pixels GTK paints outside the
-- popup's own rounded corners (popup_theme.css's border-radius: 10px) --
-- without it, blur fills the whole rectangular layer surface regardless
-- of the popup's rounded shape, showing up as square "ghosting" around
-- the rounded popup.
hl.layer_rule({ match = { namespace = "^(popup-daemon)$" }, blur = true, ignore_alpha = 0.2 })

-- Same macOS-vibrancy blur treatment for rofi (namespace confirmed via
-- `hyprctl -j layers` while it's open -- rofi-wayland just uses "rofi").
-- Same ignore_alpha as the popups above, for the same reason: keeps
-- blur off the fully-transparent pixels outside rofi-config.rasi's
-- rounded window{} corners (border-radius: 16px there).
hl.layer_rule({ match = { namespace = "^(rofi)$" }, blur = true, ignore_alpha = 0.2 })
